create table if not exists mpesa_config_entity (
    id bigint generated by default as identity primary key,
    offering_type varchar(120),
    paybill_number varchar(40),
    consumer_key varchar(500),
    consumer_secret varchar(500),
    pass_key varchar(500),
    transaction_desc varchar(500),
    deleted_flag boolean not null default false,
    suspended_flag boolean not null default false
);

create index if not exists idx_mpesa_config_offering_type on mpesa_config_entity (offering_type);
create index if not exists idx_mpesa_config_paybill_number on mpesa_config_entity (paybill_number);

create table if not exists mpesa_callbacks (
    id bigint generated by default as identity primary key,
    merchant_request_id varchar(120) not null,
    checkout_request_id varchar(120) not null,
    result_code integer not null,
    result_desc varchar(500) not null
);

create index if not exists idx_mpesa_callbacks_checkout_request_id on mpesa_callbacks (checkout_request_id);

create table if not exists callback_metadata (
    id bigint generated by default as identity primary key,
    mpesa_callback_id bigint,
    constraint fk_callback_metadata_mpesa_callback
        foreign key (mpesa_callback_id)
        references mpesa_callbacks (id)
);

create table if not exists callback_metadata_items (
    id bigint generated by default as identity primary key,
    name varchar(120) not null,
    metadata_value varchar(500) not null,
    callback_metadata_id bigint,
    constraint fk_callback_metadata_items_metadata
        foreign key (callback_metadata_id)
        references callback_metadata (id)
);

create index if not exists idx_callback_metadata_items_metadata_id on callback_metadata_items (callback_metadata_id);
